package main

import (
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"github.com/invopop/jsonschema"

	"github.com/majorcontext/harness/internal/server"
)

func render() (openapiJSON, ts []byte, err error) {
	comps, err := components()
	if err != nil {
		return nil, nil, err
	}
	openapiJSON, err = openAPI(comps)
	if err != nil {
		return nil, nil, err
	}
	return openapiJSON, typescript(comps), nil
}

func typescript(comps map[string]*jsonschema.Schema) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by go generate ./protocol; DO NOT EDIT.\n")
	names := make([]string, 0, len(comps))
	for name := range comps {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		s := comps[name]
		if s.Type == "object" && s.Properties != nil {
			fmt.Fprintf(&b, "\nexport interface %s %s\n", name, tsObject(s, "\n"))
			continue
		}
		fmt.Fprintf(&b, "\nexport type %s = %s;\n", name, tsType(s))
	}
	b.WriteString("\nexport interface Operations {\n")
	for _, r := range server.Table {
		if r.Stream {
			continue
		}
		response := tsBody(r.Response)
		if r.Raw {
			response = "Blob"
		}
		fmt.Fprintf(&b, "  %s: { query: %s; request: %s; response: %s };\n", r.Name, tsQuery(r), tsBody(r.Request), response)
	}
	b.WriteString("}\n\nexport const routes = [\n")
	for _, r := range server.Table {
		fmt.Fprintf(&b, "  { name: %q, method: %q, path: %q, status: %d, stream: %t },\n", r.Name, r.Method, r.Path, r.Status, r.Stream)
	}
	b.WriteString("] as const;\n")
	return []byte(b.String())
}

func tsQuery(r server.Route) string {
	if len(r.Query) == 0 {
		return "Record<string, never>"
	}
	parts := make([]string, len(r.Query))
	for i, q := range r.Query {
		t := "string"
		if q.Integer {
			t = "number"
		}
		parts[i] = fmt.Sprintf("%s?: %s", q.Name, t)
	}
	return "{ " + strings.Join(parts, "; ") + " }"
}

func tsBody(v any) string {
	if v == nil {
		return "void"
	}
	return tsType(schemaOf(v))
}

func tsObject(s *jsonschema.Schema, nl string) string {
	var b strings.Builder
	indent := "  "
	if nl == " " {
		indent = ""
	}
	b.WriteString("{" + nl)
	for pair := s.Properties.Oldest(); pair != nil; pair = pair.Next() {
		opt := "?"
		if slices.Contains(s.Required, pair.Key) {
			opt = ""
		}
		fmt.Fprintf(&b, "%s%s%s: %s;%s", indent, pair.Key, opt, tsType(pair.Value), nl)
	}
	b.WriteString("}")
	return b.String()
}

func tsType(s *jsonschema.Schema) string {
	switch {
	case s.Ref != "":
		return strings.TrimPrefix(s.Ref, defsPrefix)
	case len(s.AnyOf) > 0:
		parts := make([]string, len(s.AnyOf))
		for i, a := range s.AnyOf {
			parts[i] = tsType(a)
		}
		return strings.Join(parts, " | ")
	case len(s.Enum) > 0:
		parts := make([]string, len(s.Enum))
		for i, e := range s.Enum {
			raw, _ := json.Marshal(e)
			parts[i] = string(raw)
		}
		return strings.Join(parts, " | ")
	}
	switch s.Type {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		item := tsType(s.Items)
		if strings.Contains(item, " ") {
			item = "(" + item + ")"
		}
		return item + "[]"
	case "object":
		if s.Properties != nil && s.Properties.Len() > 0 {
			return tsObject(s, " ")
		}
		if s.AdditionalProperties != nil && s.AdditionalProperties != jsonschema.TrueSchema && s.AdditionalProperties != jsonschema.FalseSchema {
			return "Record<string, " + tsType(s.AdditionalProperties) + ">"
		}
		return "Record<string, unknown>"
	}
	return "unknown"
}
