func TestCheck(t *testing.T) {
	for _, tc := range checkCases {
		t.Run(tc.name, func(t *testing.T) {
			r, err := Collect(tc.fs)
			if err != nil {
				t.Fatal(err)
			}
			want := slices.Clone(tc.want)
			slices.Sort(want)
			got := rules(Check(r, tc.base))
			if !slices.Equal(got, want) {
				t.Fatalf("violations = %v, want %v", got, want)
			}
		})
	}
}

